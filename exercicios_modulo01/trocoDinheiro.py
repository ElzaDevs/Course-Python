## Calcular troco- Leia uma quantidade de segundos e converta horas para minutos+segundos.
print("================================")
compras = float(input("Suas Compras: "))
pago_dinheiro = float(input("Dinheiro pago: "))
troco_do_dinheiro = pago_dinheiro - compras
print(f"Seu troco é: {troco_do_dinheiro}")